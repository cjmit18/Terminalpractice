import { COMMAND_REFERENCE } from '../../data/commandReference';
import { DocExample, DocOption, InfoNode, LinuxDoc } from './types';

/**
 * Manual pages for every command the Linux engine runs, plus the section 5 file formats
 * named in the LPIC-1 objectives. The layout, sections, option names and option meanings
 * follow the real Ubuntu 22.04 tools; the wording is our own and kept short.
 */

const COREUTILS = 'GNU coreutils 8.32';

const o = (flags: string, desc: string): DocOption => ({ flags, desc });
const HELP = o('--help', 'show this usage summary and exit');
const VERSION = o('--version', 'show version information and exit');

/** Examples from the Command Encyclopedia entry of the same name. */
function refExamples(name: string): DocExample[] {
  const entry = COMMAND_REFERENCE.find(e => e.name === name);
  return entry ? entry.examples.map(e => ({ cmd: e.cmd, desc: e.description })) : [];
}

/** A node of the coreutils Info manual, which documents each program in "NAME invocation". */
const core = (name: string, title: string, up: string, next?: string, prev?: string): InfoNode =>
  ({ file: 'coreutils.info', node: `${name} invocation`, title: `'${name}': ${title}`, up, next, prev });

